import os, sys, paramiko
for _s in (sys.stdout, sys.stderr):
    if hasattr(_s, 'reconfigure'): _s.reconfigure(encoding='utf-8', errors='replace')
KEY = os.path.expanduser('~/.ssh/trader_vps')
b = paramiko.SSHClient(); b.set_missing_host_key_policy(paramiko.AutoAddPolicy())
b.connect('87.107.152.67', 22, username='root', pkey=paramiko.Ed25519Key.from_private_key_file(KEY), timeout=25, look_for_keys=False, allow_agent=False)
def run(cmd, t=120):
    _, so, se = b.exec_command(cmd, timeout=t)
    return so.read().decode('utf-8','replace') + se.read().decode('utf-8','replace')
print('=== packages/mcp ===')
print(run('ls /opt/umami/packages/mcp/ 2>/dev/null; cat /opt/umami/packages/mcp/package.json 2>/dev/null | head -30'))
print('=== mcp source head ===')
print(run('ls /opt/umami/packages/mcp/src 2>/dev/null; head -60 /opt/umami/packages/mcp/src/index.ts 2>/dev/null; head -40 /opt/umami/packages/mcp/README.md 2>/dev/null'))
print(run('grep -rn MCP_ENABLED /opt/umami/src --include=*.ts -l | head -4'))
print(run('ls /opt/umami/src/app/api/mcp 2>/dev/null || find /opt/umami/src/app -maxdepth 2 -name "*mcp*"'))
print('=== tools list ===')
print(run('ls /opt/umami/packages/mcp/src/tools/; grep -o "name: '"'"'[a-z_]*'"'"'" /opt/umami/packages/mcp/src/tools/*.ts 2>/dev/null | head -20'))
print('=== stdio env ===')
print(run('grep -n "UMAMI\|API_KEY\|env\." /opt/umami/packages/mcp/src/stdio.ts | head -15'))
print('=== MCP env refs in server ===')
print(run('grep -rn "MCP" /opt/umami/src/lib/constants.ts /opt/umami/src/lib/env.ts 2>/dev/null | head; grep -rln "MCP_ENABLED\|/mcp" /opt/umami/src/app 2>/dev/null | head -5'))
print('=== current env + probe ===')
print(run('grep -c MCP /etc/umami.env; cat /etc/umami.env | grep -o "^[A-Z_]*=" | sort; curl -s -o /dev/null -w "mcp-endpoint:%{http_code}" http://127.0.0.1:3001/mcp'))
b.close()